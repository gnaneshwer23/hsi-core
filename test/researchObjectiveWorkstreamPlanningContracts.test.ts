describe("research objective and workstream planning contracts (M17 PR2)", () => {
  test("drafts scientific objective with human definition and layer distinctions", () => {
    const objective = seedObjective();
    expect(objective.layerKind).toBe("scientific_objective");
    expect(objective.lifecycle).toBe("draft");
    expect(objective.definedBy.actorKind).toBe("human");
    expect(objective.honesty.autoGeneratedPlansNotApproved).toBe(true);
    expect(objective.honesty.layerDistinctionsEnforced).toBe(true);
    expect(objective.honesty.dependsOnPr1ScientificProgrammeContracts).toBe(
      true,
    );
    expect(objective.honesty.continuousEvidenceInvestigation).toBe(false);
    expect(PLANNING_LAYER_KINDS).toContain("research_question");
    expect(PLANNING_LAYER_KINDS).toContain("hypothesis");
    expect(PLANNING_LAYER_KINDS).toContain("evidence_gap");
    expect(PLANNING_LAYER_KINDS).toContain("investigation");
    expect(PLANNING_LAYER_KINDS).toContain("experiment");
    expect(PLANNING_LAYER_KINDS).toContain("research_decision");

    expect(() =>
      seedObjective({
        definedByActorKind: "ai_agent",
        definedByPrincipalId: "agent-hsi-sp-plan-1",
      }),
    ).toThrow(/Only human researchers may define/);
  });

  test("draft plan distinguishes questions, gaps, and propose-only workstreams", () => {
    const plan = seedPlan();
    expect(plan.lifecycle).toBe("draft");
    expect(plan.autoGeneratedNotApproved).toBe(true);
    expect(plan.researchQuestions[0]?.notHypothesis).toBe(true);
    expect(plan.evidenceGaps[0]?.notExperiment).toBe(true);
    expect(plan.evidenceGaps[0]?.notResearchDecision).toBe(true);
    expect(plan.proposedWorkstreams[0]?.autoGeneratedNotApproved).toBe(true);
    expect(plan.proposedWorkstreams[0]?.linkedWorkstreamId).toBeNull();
    expect(plan.requirementEstimate.notAQuotaGuarantee).toBe(true);
    expect(plan.requirementEstimate.notLiveExecutionAuthorisation).toBe(true);
    expect(plan.availableCapabilities.every((c) => c.notAuthorisedAutonomousExecution)).toBe(
      true,
    );
    expect(fingerprintProgrammePlan(plan)).toMatch(/^[a-f0-9]{64}$/);

    expect(() =>
      seedPlan(seedObjective(), {
        scopeSummary: "This auto-generated plan is approved for discovery.",
      }),
    ).toThrow(/must not invent/);
  });

  test("planning workflow enrichment preserves complete history", () => {
    const objective = seedObjective();
    let plan = draftProgrammePlan({
      id: "hsi-sp-plan-workflow-fixture",
      programmeId,
      objective,
      scopeSummary: "Initial empty planning envelope (fixture).",
      inclusionNotes: "To be enriched.",
      exclusionNotes: "No PHI.",
      authoredByPrincipalId: "agent-hsi-sp-plan-1",
      createdAt: asOf,
    });
    const store = createMemoryResearchObjectivePlanningStore();
    store.upsertObjective(objective);
    store.upsertPlan(plan);
    store.appendHistory(
      recordPlanningHistory({
        id: "hsi-sp-hist-objective-defined",
        plan,
        eventKind: "objective_defined",
        summary: "Researcher defined scientific objective.",
        actor: objective.definedBy,
        at: asOf,
      }),
    );

    const agent = {
      principalId: "agent-hsi-sp-plan-1",
      actorKind: "ai_agent" as const,
    };

    let step = enrichProgrammePlan({
      plan,
      updatedAt: asOf,
      actor: agent,
      eventKind: "scope_identified",
      historyId: "hsi-sp-hist-scope",
      historySummary: "Research scope identified.",
      scopeSummary:
        "Scoped to public SSc Tfh–IL-21 neighbourhood planning (fixture).",
      inclusionNotes: "Public evidence only.",
      exclusionNotes: "No PHI/CDS; no fabricated discoveries.",
    });
    plan = step.plan;
    store.appendHistory(step.history);

    step = enrichProgrammePlan({
      plan,
      updatedAt: asOf,
      actor: agent,
      eventKind: "knowledge_retrieved",
      historyId: "hsi-sp-hist-knowledge",
      historySummary: "Existing programme knowledge refs retrieved.",
      knowledgeRefs: [
        {
          kind: "investigation",
          refId: "inv-ssc-mech-001",
          label: null,
          graphPromotable: false,
        },
      ],
    });
    plan = step.plan;
    store.appendHistory(step.history);

    step = enrichProgrammePlan({
      plan,
      updatedAt: asOf,
      actor: agent,
      eventKind: "questions_identified",
      historyId: "hsi-sp-hist-questions",
      historySummary: "Biological research questions identified.",
      researchQuestions: seedQuestions(),
    });
    plan = step.plan;
    store.appendHistory(step.history);

    step = enrichProgrammePlan({
      plan,
      updatedAt: asOf,
      actor: agent,
      eventKind: "dependencies_mapped",
      historyId: "hsi-sp-hist-deps",
      historySummary: "Question dependencies mapped.",
      questionDependencies: [
        {
          fromQuestionId: "hsi-sp-rq-tfh-il21-neighbourhood",
          toQuestionId: "hsi-sp-rq-opposing-evidence",
          dependencyKind: "prerequisite",
          note: "Fixture dependency.",
        },
      ],
    });
    plan = step.plan;
    store.appendHistory(step.history);

    step = enrichProgrammePlan({
      plan,
      updatedAt: asOf,
      actor: agent,
      eventKind: "evidence_required",
      historyId: "hsi-sp-hist-gaps",
      historySummary: "Required evidence gaps identified.",
      evidenceGaps: seedGaps(),
    });
    plan = step.plan;
    store.appendHistory(step.history);

    step = enrichProgrammePlan({
      plan,
      updatedAt: asOf,
      actor: agent,
      eventKind: "capabilities_identified",
      historyId: "hsi-sp-hist-caps",
      historySummary: "Investigation capabilities identified.",
      availableCapabilities: seedCapabilities(),
    });
    plan = step.plan;
    store.appendHistory(step.history);

    step = enrichProgrammePlan({
      plan,
      updatedAt: asOf,
      actor: agent,
      eventKind: "workstreams_proposed",
      historyId: "hsi-sp-hist-workstreams",
      historySummary: "Workstreams proposed — not approved.",
      proposedWorkstreams: seedProposedWorkstreams(),
    });
    plan = step.plan;
    store.appendHistory(step.history);

    step = enrichProgrammePlan({
      plan,
      updatedAt: asOf,
      actor: agent,
      eventKind: "requirements_estimated",
      historyId: "hsi-sp-hist-requirements",
      historySummary: "Computational and data requirements estimated.",
      requirementEstimate: {
        computeClass: "declared_limited",
        dataClass: "fixture_engineering",
        estimateNotes: "Fixture estimate — not live authorisation.",
        notAQuotaGuarantee: true,
        notLiveExecutionAuthorisation: true,
      },
    });
    plan = step.plan;
    store.appendHistory(step.history);

    expect(plan.lifecycle).toBe("draft");
    expect(plan.autoGeneratedNotApproved).toBe(true);
    expect(plan.proposedWorkstreams).toHaveLength(2);
    expect(plan.questionDependencies).toHaveLength(1);

    const requested = requestProgrammePlanApproval({
      plan,
      updatedAt: asOf,
      actor: agent,
      historyId: "hsi-sp-hist-approval-req",
    });
    expect(requested.plan.lifecycle).toBe("awaiting_researcher_approval");
    expect(requested.plan.autoGeneratedNotApproved).toBe(true);
    expect(requested.history.eventKind).toBe("approval_requested");
    store.upsertPlan(requested.plan);
    store.appendHistory(requested.history);

    const history = store.listHistory(requested.plan.id);
    expect(history).toHaveLength(10);
    expect(history.map((h) => h.eventKind)).toEqual([
      "objective_defined",
      "scope_identified",
      "knowledge_retrieved",
      "questions_identified",
      "dependencies_mapped",
      "evidence_required",
      "capabilities_identified",
      "workstreams_proposed",
      "requirements_estimated",
      "approval_requested",
    ]);
  });

  test("refuses agent self-approval and keeps auto-generated plans unapproved", () => {
    const plan = seedPlan();
    const awaiting = requestProgrammePlanApproval({
      plan,
      updatedAt: asOf,
      actor: {principalId: "agent-hsi-sp-plan-1", actorKind: "ai_agent"},
      historyId: "hsi-sp-hist-req-2",
    }).plan;

    expect(awaiting.lifecycle).toBe("awaiting_researcher_approval");
    expect(awaiting.autoGeneratedNotApproved).toBe(true);

    expect(() =>
      transitionProgrammePlan({
        plan: awaiting,
        to: "approved",
        updatedAt: asOf,
        actor: {principalId: "agent-hsi-sp-plan-1", actorKind: "ai_agent"},
        historyId: "hsi-sp-hist-bad-approve",
      }),
    ).toThrow(/Only human researchers/);

    expect(() =>
      transitionProgrammePlan({
        plan: awaiting,
        to: "approved",
        updatedAt: asOf,
        actor: {principalId: "agent-hsi-sp-plan-1", actorKind: "human"},
        historyId: "hsi-sp-hist-self-approve",
      }),
    ).toThrow(/cannot self-approve/);

    const approved = transitionProgrammePlan({
      plan: awaiting,
      to: "approved",
      updatedAt: asOf,
      actor: {principalId: "principal-researcher-alice", actorKind: "human"},
      historyId: "hsi-sp-hist-approve",
    });
    expect(approved.plan.lifecycle).toBe("approved");
    expect(approved.plan.autoGeneratedNotApproved).toBe(true);
    expect(approved.plan.reviewedBy?.principalId).toBe(
      "principal-researcher-alice",
    );
  });

  test("allows revise scope/priorities and preserves revision history", () => {
    const awaiting = requestProgrammePlanApproval({
      plan: seedPlan(),
      updatedAt: asOf,
      actor: {principalId: "agent-hsi-sp-plan-1", actorKind: "ai_agent"},
      historyId: "hsi-sp-hist-req-3",
    }).plan;

    const revised = reviseProgrammePlanScopeOrPriorities({
      plan: awaiting,
      updatedAt: asOf,
      actor: {principalId: "principal-researcher-alice", actorKind: "human"},
      historyId: "hsi-sp-hist-revise-scope",
      revisionKind: "priorities_revised",
      historySummary:
        "Researcher raised opposing-evidence lane priority ahead of neighbourhood lane.",
      proposedWorkstreams: [
        {...seedProposedWorkstreams()[0]!, priorityOrdinal: 2},
        {...seedProposedWorkstreams()[1]!, priorityOrdinal: 1},
      ],
    });
    expect(revised.plan.lifecycle).toBe("revising");
    expect(revised.plan.planningRevision).toBe(2);
    expect(revised.plan.autoGeneratedNotApproved).toBe(true);
    expect(revised.history.eventKind).toBe("priorities_revised");
    expect(
      revised.plan.proposedWorkstreams.find(
        (w) => w.id === "hsi-sp-pw-opposing-evidence",
      )?.priorityOrdinal,
    ).toBe(1);

    expect(() =>
      reviseProgrammePlanScopeOrPriorities({
        plan: awaiting,
        updatedAt: asOf,
        actor: {principalId: "agent-hsi-sp-plan-1", actorKind: "ai_agent"},
        historyId: "hsi-sp-hist-bad-revise",
        revisionKind: "scope_revised",
        historySummary: "Agent attempted scope revise.",
        scopeSummary: "Should fail.",
      }),
    ).toThrow(/Only human researchers may revise/);
  });

  test("registers approved plan with optional PR1 workstream bindings", () => {
    const awaiting = requestProgrammePlanApproval({
      plan: seedPlan(),
      updatedAt: asOf,
      actor: {principalId: "agent-hsi-sp-plan-1", actorKind: "ai_agent"},
      historyId: "hsi-sp-hist-req-4",
    }).plan;
    const approved = transitionProgrammePlan({
      plan: awaiting,
      to: "approved",
      updatedAt: asOf,
      actor: {principalId: "principal-researcher-alice", actorKind: "human"},
      historyId: "hsi-sp-hist-approve-2",
    }).plan;

    expect(() =>
      registerApprovedProgrammePlan({
        plan: awaiting,
        updatedAt: asOf,
        actor: {principalId: "principal-researcher-alice", actorKind: "human"},
        historyId: "hsi-sp-hist-bad-register",
      }),
    ).toThrow(/Only approved plans/);

    const registered = registerApprovedProgrammePlan({
      plan: approved,
      updatedAt: asOf,
      actor: {principalId: "principal-researcher-alice", actorKind: "human"},
      historyId: "hsi-sp-hist-register",
      linkedWorkstreamBindings: [
        {
          proposedWorkstreamId: "hsi-sp-pw-evidence-neighbourhood",
          workstreamId: "hsi-sp-ws-evidence-fixture",
        },
      ],
    });
    expect(registered.plan.lifecycle).toBe("registered");
    expect(registered.plan.autoGeneratedNotApproved).toBe(true);
    expect(
      registered.plan.proposedWorkstreams.find(
        (w) => w.id === "hsi-sp-pw-evidence-neighbourhood",
      )?.linkedWorkstreamId,
    ).toBe("hsi-sp-ws-evidence-fixture");
    expect(registered.history.eventKind).toBe("plan_registered");
  });

  test("memory store round-trip and persistence pack lines", () => {
    const objective = seedObjective();
    const planDraft = seedPlan(objective);
    const awaiting = requestProgrammePlanApproval({
      plan: planDraft,
      updatedAt: asOf,
      actor: {principalId: "agent-hsi-sp-plan-1", actorKind: "ai_agent"},
      historyId: "hsi-sp-hist-store-req",
    });
    const approved = transitionProgrammePlan({
      plan: awaiting.plan,
      to: "approved",
      updatedAt: asOf,
      actor: {principalId: "principal-researcher-alice", actorKind: "human"},
      historyId: "hsi-sp-hist-store-approve",
    });
    const registered = registerApprovedProgrammePlan({
      plan: approved.plan,
      updatedAt: asOf,
      actor: {principalId: "principal-researcher-alice", actorKind: "human"},
      historyId: "hsi-sp-hist-store-register",
    });

    const store = createMemoryResearchObjectivePlanningStore();
    store.upsertObjective(objective);
    store.upsertPlan(registered.plan);
    store.appendHistory(awaiting.history);
    store.appendHistory(approved.history);
    store.appendHistory(registered.history);

    expect(store.getObjective(objective.id)?.id).toBe(objective.id);
    expect(store.listPlans(programmeId)).toHaveLength(1);
    expect(store.listHistory(registered.plan.id)).toHaveLength(3);

    const pack = buildResearchObjectivePlanningPack({
      objectives: [objective],
      plans: [registered.plan],
      history: store.listHistory(registered.plan.id),
      asOf,
    });
    expect(pack.objectiveCount).toBe(1);
    expect(pack.planCount).toBe(1);
    expect(pack.historyCount).toBe(3);
    expect(pack.honesty.autoGeneratedPlansNotApproved).toBe(true);
    expect(pack.honesty.agentsCannotSelfApprove).toBe(true);

    const lines = projectResearchObjectivePlanningPersistenceLines({
      objective,
      plan: registered.plan,
      history: store.listHistory(registered.plan.id),
    });
    expect(lines).toContain("autoGeneratedNotApproved=true");
    expect(lines).toContain("agentsCannotSelfApprove=true");
    expect(lines).toContain("layerDistinctionsEnforced=true");
    expect(lines).toContain("neon=red-wave-only");
    expect(lines).toContain("continuousEvidenceInvestigation=false");
    expect(lines).toContain("migration=deferred");
  });
});

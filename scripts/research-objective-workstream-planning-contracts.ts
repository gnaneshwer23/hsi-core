/**
 * Milestone 17 / PR2 — research objective and workstream planning pack check.
 * Offline contracts only — no auto-approval, agent self-approval, or fabricated discoveries.
 */
import {mkdirSync, writeFileSync} from "node:fs";
import {join} from "node:path";
import {
  buildResearchObjectivePlanningPack,
  draftProgrammePlan,
  draftScientificObjective,
  projectResearchObjectivePlanningPersistenceLines,
  registerApprovedProgrammePlan,
  requestProgrammePlanApproval,
  RESEARCH_OBJECTIVE_PLANNING_METHOD,
  RESEARCH_OBJECTIVE_PLANNING_SCHEMA,
  RESEARCH_OBJECTIVE_PLANNING_VERSION,
  transitionProgrammePlan,
} from "../src/researchObjectiveWorkstreamPlanningContracts";

const asOf = "2026-11-09T16:00:00.000Z";
const outDir = "evaluation/research-objective-workstream-planning";

function fixturePack() {
  const objective = draftScientificObjective({
    id: "hsi-sp-obj-fixture-demo",
    programmeId: "hsi-sp-prog-fixture-demo",
    statement:
      "Fixture scientific objective for programme planning contracts — no discovery claim.",
    successCriteria:
      "Human-approved plan with questions, gaps, and propose-only workstreams.",
    constraints:
      "Engineering fixture only — no PHI/CDS; agents cannot self-approve.",
    definedByPrincipalId: "fixture-researcher",
    definedByActorKind: "human",
    createdAt: asOf,
  });

  const draft = draftProgrammePlan({
    id: "hsi-sp-plan-fixture-demo",
    programmeId: "hsi-sp-prog-fixture-demo",
    objective,
    scopeSummary:
      "Fixture planning scope composing existing investigation/hypothesis refs.",
    inclusionNotes: "Public fixture evidence neighbourhoods only.",
    exclusionNotes:
      "No PHI, no fabricated discoveries, no auto-approved plans.",
    authoredByPrincipalId: "fixture-agent-sp-plan",
    authoredByActorKind: "ai_agent",
    createdAt: asOf,
    knowledgeRefs: [
      {
        kind: "investigation",
        refId: "inv-fixture-001",
        label: "Fixture investigation",
        graphPromotable: false,
      },
      {
        kind: "hypothesis",
        refId: "hyp-fixture-001",
        label: "Fixture hypothesis",
        graphPromotable: false,
      },
    ],
    researchQuestions: [
      {
        id: "hsi-sp-rq-fixture-neighbourhood",
        layerKind: "research_question",
        notHypothesis: true,
        question:
          "Which fixture public-evidence neighbourhoods are in scope for planning?",
        priorityOrdinal: 1,
        linkedHypothesisIds: ["hyp-fixture-001"],
        note: "Question ≠ hypothesis.",
      },
    ],
    questionDependencies: [],
    evidenceGaps: [
      {
        id: "hsi-sp-egap-fixture-coverage",
        layerKind: "evidence_gap",
        notExperiment: true,
        notResearchDecision: true,
        summary:
          "Fixture coverage gap for neighbourhood scoping — not an experiment.",
        requiredEvidenceKinds: ["public_literature", "gap_assessment"],
        addressesQuestionIds: ["hsi-sp-rq-fixture-neighbourhood"],
        note: "Gap ≠ decision.",
      },
    ],
    availableCapabilities: [
      {
        capabilityId: "m6.investigation_contract",
        availability: "available_fixture",
        notAuthorisedAutonomousExecution: true,
        note: "Fixture capability.",
      },
    ],
    proposedWorkstreams: [
      {
        id: "hsi-sp-pw-fixture-evidence",
        name: "Fixture evidence workstream proposal",
        objectiveSummary:
          "Propose public-evidence neighbourhoods for human review — not autonomous execution.",
        addressesQuestionIds: ["hsi-sp-rq-fixture-neighbourhood"],
        addressesEvidenceGapIds: ["hsi-sp-egap-fixture-coverage"],
        capabilityIds: ["m6.investigation_contract"],
        proposedAuthorisationClass: "fixture_engineering_only",
        proposedResourceClass: "fixture_unbounded_not_claimed",
        proposedDataPermissionClass: "fixture_engineering",
        linkedWorkstreamId: null,
        autoGeneratedNotApproved: true,
        priorityOrdinal: 1,
        note: "Proposal only.",
      },
    ],
    requirementEstimate: {
      computeClass: "fixture_unbounded_not_claimed",
      dataClass: "fixture_engineering",
      estimateNotes:
        "Fixture estimate only — not a quota guarantee and not live execution authorisation.",
      notAQuotaGuarantee: true,
      notLiveExecutionAuthorisation: true,
    },
  });

  const requested = requestProgrammePlanApproval({
    plan: draft,
    updatedAt: asOf,
    actor: {principalId: "fixture-agent-sp-plan", actorKind: "ai_agent"},
    historyId: "hsi-sp-hist-fixture-req",
  });
  const approved = transitionProgrammePlan({
    plan: requested.plan,
    to: "approved",
    updatedAt: asOf,
    actor: {principalId: "fixture-researcher", actorKind: "human"},
    historyId: "hsi-sp-hist-fixture-approve",
  });
  const registered = registerApprovedProgrammePlan({
    plan: approved.plan,
    updatedAt: asOf,
    actor: {principalId: "fixture-researcher", actorKind: "human"},
    historyId: "hsi-sp-hist-fixture-register",
    linkedWorkstreamBindings: [
      {
        proposedWorkstreamId: "hsi-sp-pw-fixture-evidence",
        workstreamId: "hsi-sp-ws-fixture-demo",
      },
    ],
  });

  const history = [
    requested.history,
    approved.history,
    registered.history,
  ];
  const pack = buildResearchObjectivePlanningPack({
    objectives: [objective],
    plans: [registered.plan],
    history,
    asOf,
  });
  const persistenceLines = projectResearchObjectivePlanningPersistenceLines({
    objective,
    plan: registered.plan,
    history,
  });

  return {pack, persistenceLines};
}

function writeOutputs() {
  mkdirSync(outDir, {recursive: true});
  const {pack, persistenceLines} = fixturePack();
  writeFileSync(
    join(outDir, "research-objective-workstream-planning-pack.v1.json"),
    `${JSON.stringify(pack, null, 2)}\n`,
  );
  writeFileSync(
    join(outDir, "STATUS.json"),
    `${JSON.stringify(
      {
        schema: RESEARCH_OBJECTIVE_PLANNING_SCHEMA,
        method: RESEARCH_OBJECTIVE_PLANNING_METHOD,
        version: RESEARCH_OBJECTIVE_PLANNING_VERSION,
        asOf,
        status: "engineering_fixture_ok",
        scientificApproval: false,
        autoGeneratedPlansNotApproved: true,
        agentsCannotSelfApprove: true,
        reviseScopePrioritiesAllowed: true,
        completePlanningHistoryPreserved: true,
        layerDistinctionsEnforced: true,
        notSeparateAgentPlatform: true,
        noAutoApprovalOfPlansOrClaims: true,
        noFabricatedDiscoveries: true,
        workbenchUi: false,
        neonProjectPolicy: "red-wave-only",
        migration: "deferred",
        continuousEvidenceInvestigation: false,
        persistenceLineCount: persistenceLines.length,
        persistenceLines,
      },
      null,
      2,
    )}\n`,
  );
}

const checkOnly = process.argv.includes("--check");
if (checkOnly) {
  const {pack} = fixturePack();
  if (
    pack.objectiveCount !== 1 ||
    pack.planCount !== 1 ||
    pack.historyCount !== 3
  ) {
    throw new Error("Research objective planning pack check failed");
  }
  if (pack.honesty.autoGeneratedPlansNotApproved !== true) {
    throw new Error("Auto-generated plan honesty gate failed");
  }
  if (pack.honesty.agentsCannotSelfApprove !== true) {
    throw new Error("Self-approval honesty gate failed");
  }
  if (pack.plans[0]?.lifecycle !== "registered") {
    throw new Error("Expected registered plan in fixture pack");
  }
  if (pack.plans[0]?.autoGeneratedNotApproved !== true) {
    throw new Error("Registered plan must retain autoGeneratedNotApproved");
  }
  console.log("research-objective-workstream-planning contracts check ok");
} else {
  writeOutputs();
  console.log(`wrote ${outDir}`);
}

/**
 * Generate docs/STATUS.md from the capability register.
 * The register remains the source. This page is the status readers should open.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { HELD_MIGRATION_IDS } from "../src/db/migrationHolds";

export type CapabilityLevel = "implemented" | "partial" | "stub" | "absent";

export type CapabilityRow = {
  id: string;
  group: string;
  name: string;
  status: string[];
  evidence: string[];
  gap: string;
  nextAction: string;
  acceptance?: { deployment: "not_assessed" | "not_verified" | "blocked" | "not_applicable"; scientific: "not_assessed" | "not_accepted" | "not_applicable" };
};

const REGISTER = "operations/capability-register/capability-register.v1.json";
const STATUS_DOC = "docs/STATUS.md";

const SUPERSEDED = [
  "docs/BUILD_STATUS_AND_NEXT.md",
  "docs/PRD_IMPLEMENTATION_AUDIT.md",
  "docs/OUTPUTS.md",
  "docs/engineering/PRODUCTION_READINESS_AUDIT_2026-11-08.md",
  "docs/engineering/HSI_CAPABILITY_REGISTER_2026-11-08.md",
] as const;

export function capabilityLevel(status: readonly string[]): CapabilityLevel {
  const flags = new Set(status);
  const implemented = flags.has("implemented") || flags.has("connected");
  const limited = flags.has("blocked") || flags.has("synthetic_only") || flags.has("planned");
  if (implemented && limited) return "partial";
  if (implemented) return "implemented";
  if (flags.has("synthetic_only")) return "stub";
  if (flags.has("blocked")) return "partial";
  if (flags.has("planned")) return "absent";
  return "absent";
}

export function renderStatusMarkdown(register: {
  registerId: string;
  asOf: string;
  honesty: Record<string, unknown>;
  capabilities: CapabilityRow[];
}): string {
  const counts: Record<CapabilityLevel, number> = { implemented: 0, partial: 0, stub: 0, absent: 0 };
  const lines = register.capabilities.map((row) => {
    const level = capabilityLevel(row.status);
    counts[level] += 1;
    const deployment = row.acceptance?.deployment ?? "not_assessed";
    const scientific = row.acceptance?.scientific ?? "not_assessed";
    const evidence = row.evidence.map((item) => `\`${item}\``).join(", ");
    return `| ${row.id} | ${row.group} | ${row.name} | ${level} | ${row.status.join(", ")} | ${deployment} | ${scientific} | ${evidence} | ${row.gap} |`;
  });
  return `# HSI status

Generated from \`${REGISTER}\`. Do not edit this file by hand. Run \`bun run status:write\`.

Register \`${register.registerId}\` as of ${register.asOf}.

| Level | Count | Meaning |
| --- | --- | --- |
| implemented | ${counts.implemented} | Working code, not only a contract |
| partial | ${counts.partial} | Real code with a blocker, a fixture limit, or incomplete coverage |
| stub | ${counts.stub} | Types, fixtures or proposal-only adapters |
| absent | ${counts.absent} | Planned or not present |

Deployment and scientific columns are independently recorded acceptance states; missing values mean **not assessed**, never accepted. Engineering vocabulary, including a historic \`scientifically_validated\` flag, cannot fill either column automatically.

These levels are derived from the register vocabulary (\`implemented\`, \`connected\`, \`blocked\`, \`synthetic_only\`, \`planned\`, \`scientifically_validated\`). A row that is both implemented and blocked is **partial**. Nothing in this table is a claim of clinical validation, regulatory approval or a live patient deployment.

## Honesty

${Object.entries(register.honesty)
  .map(([key, value]) => `- \`${key}\`: ${JSON.stringify(value)}`)
  .join("\n")}

Database deployment is **not** inferred from repository labels, merged PRs or CI. Current deployment, source/science and scope-specific security acceptance need independently verified artifacts. Historical database observations must retain their target, time and limitations; they do not establish the current ledger.

Normal migration execution skips the following ids from the shared, side-effect-free \`HELD_MIGRATION_IDS\` source (\`src/db/migrationHolds.ts\`). This is a repository hold policy, **not** proof that SQL was never manually applied to any database. No hold is removed or release authorised by this document. Apply/rehearse only the exact independently reviewed scope against HSI's approved project.

${HELD_MIGRATION_IDS.map((id) => `- \`${id}\``).join("\n")}

Current implementation-to-acceptance reconciliation: \`docs/audits/HSI_IMPLEMENTATION_TRUTH_AND_NEXT_PRS.md\` and \`operations/production-delivery/implementation-truth.v1.json\`. These metadata documents cannot authorise runtime activation.

## Capabilities

| ID | Group | Name | Engineering level | Register status | Deployment acceptance | Scientific acceptance | Evidence | Gap |
| --- | --- | --- | --- | --- | --- | --- | --- | --- |
${lines.join("\n")}

## Superseded status documents

The following documents are historical. They are not the current status:

${SUPERSEDED.map((path) => `- \`${path}\``).join("\n")}
`;
}

export const SUPERSEDED_BANNER = "**Superseded.**";

export function supersededBanner(path: string): string {
  const link = path.startsWith("docs/engineering/") ? "../STATUS.md" : "./STATUS.md";
  return `> **Superseded.** Current capability status is generated in [${link}](${link}) from \`operations/capability-register/capability-register.v1.json\`. This document is historical and is not the status source of truth.\n\n`;
}

function main(): void {
  const cwd = process.cwd();
  const register = JSON.parse(readFileSync(resolve(cwd, REGISTER), "utf8")) as {
    registerId: string;
    asOf: string;
    honesty: Record<string, unknown>;
    capabilities: CapabilityRow[];
  };
  const markdown = renderStatusMarkdown(register);
  const check = process.argv.includes("--check");
  const statusPath = resolve(cwd, STATUS_DOC);
  if (check) {
    const current = readFileSync(statusPath, "utf8");
    if (current !== markdown) {
      throw new Error(`${STATUS_DOC} is stale. Run bun run status:write.`);
    }
    for (const path of SUPERSEDED) {
      const body = readFileSync(resolve(cwd, path), "utf8");
      if (!body.includes(SUPERSEDED_BANNER)) {
        throw new Error(`${path} is missing the superseded banner.`);
      }
    }
    return;
  }
  writeFileSync(statusPath, markdown);
  for (const path of SUPERSEDED) {
    const full = resolve(cwd, path);
    const body = readFileSync(full, "utf8");
    if (body.includes(SUPERSEDED_BANNER)) continue;
    writeFileSync(full, supersededBanner(path) + body);
  }
}

if (import.meta.main) main();
